"""Helpers for writing scenario YAML files."""
import yaml


class _Dumper(yaml.SafeDumper):
    pass


def _str_presenter(dumper, data):
    if '\n' in data:
        return dumper.represent_scalar('tag:yaml.org,2002:str', data, style='|')
    return dumper.represent_scalar('tag:yaml.org,2002:str', data)


_Dumper.add_representer(str, _str_presenter)


def write_scenario(path, doc):
    with open(path, 'w') as f:
        f.write('# Generated by %s - do not edit by hand\n' % doc.pop('_generator', 'generator'))
        f.write(yaml.dump(doc, Dumper=_Dumper, sort_keys=False, width=1000, allow_unicode=True))


def rule(name, value=None, operator='equal', type='string', **kw):
    r = {'name': name, 'type': type, 'operator': operator}
    if value is not None:
        r['value'] = value
    r.update(kw)
    return r
