#!/bin/bash
# Writes cpanfile.pinned and dists.pinned: the CPAN distributions of the Perl GADS used for
# the reference results (the local::lib of this host, ~/perl5), each at the
# exact version installed, so that the image runs the same code.
#   docker/perl/gen-cpanfile.sh [~/perl5]
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
LL="${1:-$HOME/perl5}"
# The modules whose file declares no $VERSION (so that cpanm cannot check
# an exact version once installed) are listed without one
python3 - "$LL" > "$HERE/cpanfile.pinned" <<'PY'
import glob, json, os, subprocess, sys
ll = sys.argv[1]
meta = glob.glob(os.path.join(ll, 'lib/perl5/*/.meta/*/install.json'))
rows, seen = [], set()
for f in sorted(meta):
    j = json.load(open(f))
    name, version = j.get('name'), j.get('version')
    if not name or name in seen or name == 'local::lib':
        continue
    seen.add(name)
    rows.append((name, version))
# Parse (not load) the declared version of each installed module
script = r"""
use ExtUtils::MakeMaker;
while (my $m = <STDIN>) {
    chomp $m;
    (my $f = "$m.pm") =~ s{::}{/}g;
    my ($path) = grep { -f } map { "$_/$f" } @INC;
    my $v = $path ? MM->parse_version($path) : 'undef';
    print "$m\t", (defined $v && $v ne 'undef' ? $v : ''), "\n";
}
"""
out = subprocess.run(['perl', '-I%s/lib/perl5' % ll, '-Mlocal::lib=%s' % ll, '-e', script],
                     input='\n'.join(n for n, _ in rows), capture_output=True, text=True, check=True).stdout
declared = dict(l.split('\t', 1) for l in out.splitlines())
print('# Generated by gen-cpanfile.sh from %d installed distributions - do not edit' % len(rows))
for name, version in rows:
    if declared.get(name, ''):
        print("requires '%s', '== %s';" % (name, version))
    else:
        print("requires '%s'; # %s (declares no version)" % (name, version))
PY
# The same distributions as archives (AUTHOR/Dist-version.tar.gz), in the
# order in which they were installed, so that each one's dependencies are
# installed (at their pinned versions) before it
python3 - "$LL" > "$HERE/dists.pinned" <<'PY'
import glob, json, os, sys
meta = glob.glob(os.path.join(sys.argv[1], 'lib/perl5/*/.meta/*/install.json'))
print('# Generated by gen-cpanfile.sh - do not edit')
for f in sorted(meta, key=os.path.getmtime):
    j = json.load(open(f))
    if j.get('name') == 'local::lib' or not j.get('pathname'):
        continue
    print(j['pathname'].split('/', 2)[2])
PY
echo "Wrote $HERE/dists.pinned"
echo "Wrote $HERE/cpanfile.pinned ($(grep -c '^requires' "$HERE/cpanfile.pinned") distributions)"
