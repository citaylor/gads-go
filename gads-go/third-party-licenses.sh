#!/bin/sh
# Writes THIRD-PARTY-LICENSES: the licence texts of the code compiled into
# the gads binary (with either SQLite driver), which their licences require
# to accompany it, after the project's NOTICE (which lists GADS and the
# other works). Run it from gads-go/ after changing go.mod or NOTICE; CI
# checks that the file is current. The Docker image installs it, because
# its build context (gads-go/) does not include NOTICE.
set -eu
out=${1:-THIRD-PARTY-LICENSES}
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

section() {
	printf '%s\n' '================================================================================'
	printf '%s\n' "$1"
	printf '%s\n\n' '================================================================================'
}

{
	echo "Licences of the third-party code compiled into gads."
	echo "Generated by third-party-licenses.sh from NOTICE and gads-go/go.mod; do not edit."
	echo

	section "NOTICE"
	cat ../NOTICE
	echo

	section "Go standard library ($(go env GOVERSION))"
	cat "$(go env GOROOT)/LICENSE"
	echo

	section "Lua 5.3.6 (internal/lua)"
	# The licence is at the end of lua.h
	sed -n '/^\* Copyright (C) 1994/,/^\*\*\*\*\*\*\*\*/p' internal/lua/lua.h |
		sed -e 's/^\* \{0,1\}//' -e '/^\*\*\*\*/d'
	echo

	for tags in "" modernc; do
		go list -tags "$tags" -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/gads
	done | sort -u | while read -r path version dir; do
		section "$path $version"
		found=
		for f in "$dir"/LICENSE* "$dir"/LICENCE* "$dir"/COPYING* "$dir"/NOTICE*; do
			[ -f "$f" ] || continue
			[ -n "$found" ] && printf '\n--- %s ---\n\n' "$(basename "$f")"
			cat "$f"
			found=1
		done
		[ -n "$found" ] || { echo "no licence file in $path" >&2; exit 1; }
		echo
	done
} > "$tmp"
chmod 644 "$tmp"
mv "$tmp" "$out"
trap - EXIT
