// recordPDF is Record pdf: the record with the fields that the user can
// read (GADS::PDFGenerator)
func (c *Ctx) recordPDF(record *gads.Record, site *gads.Site) []byte {
	layout := record.Layout()
	g := c.pdfGenerator(record, layout.AllUserRead(), record.User())
	g.Marking = layout.SecurityMarking()
	g.Logo = siteLogo(site)
	g.Title = "Record " + fmtInt(record.CurrentID())
	return buildPDF(g)
}

// reportPDF is Record get_report, then Result::Report create_pdf: the
// record with the fields of a report
func (c *Ctx) reportPDF(record *gads.Record, reportID string, user *gads.User) []byte {
	row := c.E.FindReportWithPermission(reportID, user, record.Layout().InstanceID)
	if row == nil {
		gads.Fail("Report ID %s not found", reportID)
	}
	id, _ := db.AsInt64(row["id"])
	include := map[int64]bool{}
	for _, l := range c.E.ReportLayoutIDs(id) {
		include[l] = true
	}
	var cols []*gads.Column
	for _, col := range record.ColumnsRender() {
		if include[col.ID] {
			cols = append(cols, col)
		}
	}
	g := c.pdfGenerator(record, cols, user)
	instanceID, _ := db.AsInt64(row["instance_id"])
	instance := c.E.NewLayout(instanceID, user)
	// _read_security_marking: the report's, else its table's
	g.Marking, _ = db.AsString(row["security_marking"])
	if !truthy(g.Marking) {
		g.Marking = instance.SecurityMarking()
	}
	g.Logo = siteLogo(c.Site())
	title, _ := db.AsString(row["title"])
	name, _ := db.AsString(row["name"])
	switch {
	case truthy(title):
		g.Title = title
	case truthy(name):
		g.Title = name
	default:
		g.Title = "Report"
	}
	if d, _ := db.AsString(row["description"]); truthy(d) {
		g.Subtitle = d
	}
	return buildPDF(g)
}

// siteLogo is the site's logo (Site create_temp_logo)
func siteLogo(site *gads.Site) []byte {
	if site == nil {
		return nil
	}
	logo, _ := db.AsString(site.Row()["site_logo"])
	return []byte(logo)
}

// buildPDF builds the PDF, its errors being those of Perl's modules
func buildPDF(g *pdf.Generator) []byte {
	out, err := g.Build()
	if err != nil {
		gads.Panic("%s", err.Error())
	}
	return out
}

// pdfGenerator is GADS::PDFGenerator build: the topics of the record's
// presentation (presentation_map_columns and get_topics), and the lines
// of who edited it and who made the PDF
func (c *Ctx) pdfGenerator(record *gads.Record, cols []*gads.Column, user *gads.User) *pdf.Generator {
	g := &pdf.Generator{}
	topics := map[int64]int{}
	for _, col := range cols {
		var topicID int64
		var topicName string
		if col.TopicID != nil {
			if r := c.E.DB.QueryRow(`SELECT * FROM "topic" WHERE "id" = ?`, *col.TopicID); r != nil {
				topicID = *col.TopicID
				topicName, _ = db.AsString(r["name"])
			}
		}
		i, ok := topics[topicID]
		if !ok {
			name := "Other"
			if topicID != 0 {
				name = topicName
			}
			i = len(g.Topics)
			topics[topicID] = i
			g.Topics = append(g.Topics, pdf.GeneratorTopic{Name: name})
		}
		dp := c.datumPresentation(record.GetFieldValue(col))
		f := pdf.GeneratorField{Name: col.Name}
		if sv, ok := dp.get("selected_values"); ok && sv != nil {
			f.IsSelected = true
			if list, ok := sv.(*tt.List); ok {
				for _, item := range list.Items {
					var values []*string
					if h, ok := item.(*tt.Hash); ok {
						if vs, ok := h.Get("values"); ok {
							if vl, ok := vs.(*tt.List); ok {
								for _, v := range vl.Items {
									values = append(values, pdfString(v))
								}
							}
						}
					}
					f.Selected = append(f.Selected, values)
				}
			}
		} else {
			if v, ok := dp.get("value"); ok {
				f.Value = pdfString(v)
			}
			if v, ok := dp.get("grade"); ok {
				f.Grade = pdfString(v)
			}
		}
		g.Topics[i].Fields = append(g.Topics[i].Fields, f)
	}
	g.LastEdited = "Last edited by " + record.EditedUser().AsString() + " on " + record.EditedTime().AsString()
	now := c.E.Now()
	var by string
	if user != nil {
		by = user.Value
	}
	g.GeneratedBy = "Report generated by " + by + " on " + gads.FormatDate(now, c.E.Config.DateFormat) + " at " + now.Format("15:04:05")
	return g
}

// pdfString is a value of a presentation (nil for undef)
func pdfString(v any) *string {
	if v == nil {
		return nil
	}
	s := tt.Str(v)
	return &s
}
