	rt.Add([]string{"get", "post"}, "/api/:sheet/records", RequireLogin(s.hAPIRecords))
	rt.Add([]string{"post"}, "/api/settings/logo", RequireLogin(s.hAPISettingsLogo))
	rt.Add([]string{"get", "post"}, "/api/users", RequireAnyRole([]string{"useradmin", "superadmin"}, s.hAPIUsers))
	rt.Add([]string{"get"}, "/api/get_key", RequireLogin(s.hAPIGetKey))
