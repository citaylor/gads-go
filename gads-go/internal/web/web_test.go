// _decode_json_body: the content type and JSON errors, and the object
func TestDecodeJSONBody(t *testing.T) {
	body := func(ct, b string) *Ctx {
		c := testCtx()
		c.Req = httptest.NewRequest("POST", "/", strings.NewReader(b))
		c.Req.Header.Set("Content-Type", ct)
		c.rawBody = []byte(b)
		return c
	}
	for _, x := range []struct{ ct, body, err string }{
		{"application/x-www-form-urlencoded", "a=1", "Request must be of type application/json"},
		{"application/json", "{not json", "Failed to decode JSON"},
		{"application/json", "0", "Failed to decode JSON"},
	} {
		err := gads.Try(func() { body(x.ct, x.body).decodeJSONBody() })
		if err == nil || !strings.Contains(err.Error(), x.err) {
			t.Errorf("%q: error %v, want %s", x.body, err, x.err)
		}
	}
	m := body("application/json; charset=UTF-8", `{"email":"a@b.c","groups":[1]}`).decodeJSONBody()
	if m["email"] != "a@b.c" || len(m["groups"].([]any)) != 1 {
		t.Errorf("decoded %#v", m)
	}
}

