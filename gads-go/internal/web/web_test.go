func TestSessionStoreIdle(t *testing.T) {
	st := newSessionStore(time.Hour)
	s := &Session{ID: "a", Data: map[string]any{}}
	st.put(s)
	if st.get("a") != s {
		t.Fatal("session not found")
	}
	s.used = time.Now().Add(-2 * time.Hour)
	if st.get("a") != nil {
		t.Error("idle session not expired")
	}
	// Without an idle timeout sessions are kept
	st = newSessionStore(0)
	st.put(s)
	s.used = time.Now().Add(-1000 * time.Hour)
	if st.get("a") != s {
		t.Error("session expired without an idle timeout")
	}
}
