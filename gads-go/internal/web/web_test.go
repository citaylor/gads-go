// Routes match as Dancer2::Core::Route (tokens, optional parts, prefixes,
// unanchored regexps)
func TestRouteMatching(t *testing.T) {
	rt := &Router{}
	rt.Get("/ping", nil)
	rt.Get("/myaccount/?", nil)
	rt.Add([]string{"post"}, "/api/user_account/?:id?", nil)
	rt.Get("/edit:id", nil)
	rt.AddRegexp([]string{"get"}, `/(record|history)/([0-9]+)`, nil)
	rt.Prefix("/:layout_name", func() {
		rt.Get("/?", nil)
		rt.Get("/data_graph/:id/:time", nil)
		rt.Prefix("/report", func() { rt.Get("", nil) })
	})
	cases := []struct {
		method, path, spec string
		params             map[string]string
		splat              []string
	}{
		{"GET", "/ping", "/ping", nil, nil},
		{"HEAD", "/ping", "/ping", nil, nil},
		{"GET", "/myaccount", "/myaccount/?", nil, nil},
		{"GET", "/myaccount/", "/myaccount/?", nil, nil},
		{"POST", "/api/user_account/", "/api/user_account/?:id?", nil, nil},
		{"POST", "/api/user_account/3", "/api/user_account/?:id?", map[string]string{"id": "3"}, nil},
		{"GET", "/edit5", "/edit:id", map[string]string{"id": "5"}, nil},
		{"GET", "/record/12", `/(record|history)/([0-9]+)`, nil, []string{"record", "12"}},
		// Regexp routes without a prefix are not anchored
		{"GET", "/table1/history/3/x", `/(record|history)/([0-9]+)`, nil, []string{"history", "3"}},
		{"GET", "/table1", "/:layout_name/?", map[string]string{"layout_name": "table1"}, nil},
		{"GET", "/table1/data_graph/4/123", "/:layout_name/data_graph/:id/:time", map[string]string{"layout_name": "table1", "id": "4", "time": "123"}, nil},
		{"GET", "/t/report", "/:layout_name/report", map[string]string{"layout_name": "t"}, nil},
	}
	for _, tc := range cases {
		m := rt.match(tc.method, tc.path)
		if len(m) == 0 {
			t.Errorf("%s %s: no match", tc.method, tc.path)
			continue
		}
		if m[0].r.spec != tc.spec {
			t.Errorf("%s %s: matched %s, want %s", tc.method, tc.path, m[0].r.spec, tc.spec)
		}
		for k, v := range tc.params {
			if m[0].params[k] != v {
				t.Errorf("%s %s: param %s = %q, want %q", tc.method, tc.path, k, m[0].params[k], v)
			}
		}
		if strings.Join(m[0].splat, ",") != strings.Join(tc.splat, ",") {
			t.Errorf("%s %s: splat %v, want %v", tc.method, tc.path, m[0].splat, tc.splat)
		}
	}
	if m := rt.match("POST", "/ping"); len(m) != 0 {
		t.Errorf("POST /ping matched a GET route")
	}
	if m := rt.match("GET", "/a/b/c"); len(m) != 0 {
		t.Errorf("/a/b/c matched %s", m[0].r.spec)
	}
}

// Passwords validate as Crypt::SaltedHash with a 4 byte salt
func TestPasswords(t *testing.T) {
	// Generated by Perl: "password" with salt "salt"
	perl := "{SSHA512}+mohhbPgqahe9B/7Z+88H7b3SYD46/lw5OcuNT7ZU31ZMIPCAd/W5D4cinqsK8jbsRnH37fUuPExEROVvXDpf3NhbHQ="
	if !MatchPassword("password", perl) {
		t.Error("Perl hash not validated")
	}
	if MatchPassword("Password", perl) {
		t.Error("wrong password validated")
	}
	h := HashPassword("secret")
	if !strings.HasPrefix(h, "{SSHA512}") || !MatchPassword("secret", h) || MatchPassword("other", h) {
		t.Errorf("HashPassword round trip failed: %s", h)
	}
	if MatchPassword("", "") || MatchPassword("x", "") {
		t.Error("blank stored password validated")
	}
	if !MatchPassword("plain", "plain") {
		t.Error("plain text password not compared")
	}
}

