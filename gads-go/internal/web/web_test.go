// DateTime subtract_datetime and the calendar period derived from it
func TestCalendarView(t *testing.T) {
	d := func(s string) time.Time { v, _ := time.Parse("2006-01-02 15:04:05", s); return v }
	cases := []struct{ from, to, want string }{
		{"2014-10-01 00:00:00", "2014-11-01 00:00:00", "month"},
		{"2014-10-05 00:00:00", "2014-10-12 00:00:00", "week"},
		{"2014-10-03 23:00:00", "2014-10-04 23:00:00", "day"},
		{"2014-01-01 00:00:00", "2015-01-01 00:00:00", "year"},
		{"2014-01-01 00:00:00", "2014-12-01 00:00:00", "year"},
		{"2014-09-28 00:00:00", "2014-11-09 00:00:00", "month"},
	}
	for _, c := range cases {
		if got := calendarView(d(c.from), d(c.to)); got != c.want {
			t.Errorf("calendarView(%s, %s) = %s, want %s", c.from, c.to, got, c.want)
		}
	}
	// Borrowing days from the month of the earlier date
	if got := subtractDatetime(d("2014-03-01 00:00:00"), d("2014-01-31 00:00:00")); got.months != 1 || got.days != 1 {
		t.Errorf("subtract_datetime = %+v", got)
	}
	if got := subtractDatetime(d("2014-01-01 00:00:00"), d("2014-01-02 12:00:00")); got.days != -1 || got.minutes != -720 {
		t.Errorf("negative subtract_datetime = %+v", got)
	}
}

