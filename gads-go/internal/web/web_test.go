// The sort of a column presentation (GADS::Role::Presentation::Column)
func TestPresentationSort(t *testing.T) {
	get := func(p *ttPresentation, k string) string {
		h := p.sortHash().(interface{ Get(string) (any, bool) })
		v, _ := h.Get(k)
		s, _ := v.(string)
		return s
	}
	col := &gads.Column{ID: 8}
	asc := &ttPresentation{col: col, o: presentOpts{sort: &gads.SortSpec{ID: 8, Type: "asc"}}}
	if get(asc, "link") != "8desc" || get(asc, "aria") != "ascending" || get(asc, "current") != "&darr;" {
		t.Errorf("ascending sort of the column")
	}
	desc := &ttPresentation{col: col, o: presentOpts{sort: &gads.SortSpec{ID: 8, Type: "desc"}}}
	if get(desc, "link") != "8asc" || get(desc, "text") != "ascending" || get(desc, "current") != "&uarr;" {
		t.Errorf("descending sort of the column")
	}
	other := &ttPresentation{col: col, o: presentOpts{sort: &gads.SortSpec{ID: 9, Type: "desc"}}}
	if get(other, "type") != "none" || get(other, "link") != "8asc" || get(other, "symbol") != "&darr;" {
		t.Errorf("sort of another column")
	}
	if (&ttPresentation{col: col}).sortHash() != nil {
		t.Errorf("no sort")
	}
}

