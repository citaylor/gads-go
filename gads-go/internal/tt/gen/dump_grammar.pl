#!/usr/bin/perl
# Generate grammar_tables.go from Template::Grammar (the LALR(1) tables that
# Template Toolkit compiles from parser/Parser.yp), so that the Go parser
# accepts and rejects exactly the same templates as TT.
use strict;
use warnings;
use Template::Grammar;

my $g = Template::Grammar->new;
my ($states, $rules, $lex) = @$g{qw(STATES RULES LEXTABLE)};

sub qs { my $s = shift; $s =~ s/(["\\])/\\$1/g; "\"$s\"" }

print "// Code generated by gen/dump_grammar.pl from Template::Grammar $Template::Grammar::VERSION. DO NOT EDIT.\n\n";
print "package tt\n\n";
print "var lexTable = map[string]string{\n";
print "\t", qs($_), ": ", qs($lex->{$_}), ",\n" foreach sort keys %$lex;
print "}\n\n";
print "var grammarRules = []grammarRule{\n";
foreach my $i (0..$#$rules)
{
    my ($lhs, $len) = @{$rules->[$i]};
    print "\t{", qs($lhs), ", $len},\n";
}
print "}\n\n";
print "var grammarStates = []grammarState{\n";
foreach my $s (@$states)
{
    my @parts;
    if (my $a = $s->{ACTIONS})
    {
        push @parts, "actions: map[string]int{" . join(", ", map { qs($_) . ": $a->{$_}" } sort keys %$a) . "}";
    }
    push @parts, "def: $s->{DEFAULT}, hasDef: true" if defined $s->{DEFAULT};
    if (my $go = $s->{GOTOS})
    {
        push @parts, "gotos: map[string]int{" . join(", ", map { qs($_) . ": $go->{$_}" } sort keys %$go) . "}";
    }
    print "\t{", join(", ", @parts), "},\n";
}
print "}\n";
