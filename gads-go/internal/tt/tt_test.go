// addrRe is the address in Perl's form of a reference (HASH(0x...))
var addrRe = regexp.MustCompile(`\(0x[0-9a-f]+\)`)

// TestGolden renders the templates of testdata/cases.txt and compares them
// with Template Toolkit's results (testdata/golden.json, generated by
// conformance/perl/gen_tt_golden.pl). An error is compared by its type.
func TestGolden(t *testing.T) {
	data, err := os.ReadFile("testdata/golden.json")
	if err != nil {
		t.Fatal(err)
	}
	var g struct {
		Cases []struct {
			Template string  `json:"template"`
			Out      *string `json:"out"`
			Error    string  `json:"error"`
		} `json:"cases"`
	}
	if err := json.Unmarshal(data, &g); err != nil {
		t.Fatal(err)
	}
	for i, c := range g.Cases {
		e := NewEngine("/t")
		e.Load = func(p string) ([]byte, error) {
			if p == "/t/case.tt" {
				return []byte(c.Template), nil
			}
			return nil, os.ErrNotExist
		}
		out, err := e.Process("case.tt", nil)
		switch {
		case c.Out == nil:
			var ex *Exception
			if !errors.As(err, &ex) || ex.Type != c.Error {
				t.Errorf("case %d: %s\n  error %v, Perl a %s error", i+1, c.Template, err, c.Error)
			}
		case err != nil:
			t.Errorf("case %d: %s\n  error %v, Perl %q", i+1, c.Template, err, *c.Out)
		case addrRe.ReplaceAllString(out, "(ADDR)") != addrRe.ReplaceAllString(*c.Out, "(ADDR)"):
			t.Errorf("case %d: %s\n  got  %q\n  Perl %q", i+1, c.Template, out, *c.Out)
		}
	}
}

// A template that includes itself is an error (RECURSION off, as
// Template::Document's _HOT), and blocks nested without end stop at
// maxDepth rather than overflowing the stack
func TestRecursion(t *testing.T) {
	e := NewEngine("/t")
	e.Load = func(p string) ([]byte, error) {
		switch p {
		case "/t/self.tt":
			return []byte(`[% TRY %][% INCLUDE self.tt %][% CATCH file %][% error.info %][% END %]`), nil
		case "/t/block.tt":
			return []byte(`[% BLOCK r %][% INCLUDE r %][% END %][% TRY %][% INCLUDE r %][% CATCH file %][% error.info %][% END %]`), nil
		}
		return nil, os.ErrNotExist
	}
	if out, err := e.Process("self.tt", nil); err != nil || out != "recursion into 'self.tt'" {
		t.Errorf("self: %q %v", out, err)
	}
	if out, err := e.Process("block.tt", nil); err != nil || out != "recursion into 'r' over 1000 levels" {
		t.Errorf("block: %q %v", out, err)
	}
}
