const password = "correct horse battery staple"

// passwordOutput is the scheme and length of a hash and whether the
// password matches it (the salt is random)
func passwordOutput(v any) string {
	h := v.(string)
	scheme, b64, _ := strings.Cut(strings.TrimPrefix(h, "{"), "}")
	raw, _ := base64.StdEncoding.DecodeString(b64)
	return fmt.Sprintf("%s %d %s", scheme, len(raw), perlString(web.MatchPassword(password, h)))
}

// Result is the measurement of a unit: the mean time of a run in each of
// the samples (NsPerOp is their median) and the SHA-256 of its output.
type Result struct {
	Name         string    `json:"name"`
	Iterations   int       `json:"iterations"`
	NsPerOp      float64   `json:"ns_per_op"`
	MinNs        float64   `json:"min_ns"`
	MaxNs        float64   `json:"max_ns"`
	Samples      []float64 `json:"samples"`
	OutputSHA256 string    `json:"output_sha256"`
}

// Samples is the number of samples of a unit's measurement
const Samples = 5

// Output is the text of the result of a unit's operation
func Output(u Unit, v any) string {
	if u.Output != nil {
		return u.Output(v)
	}
	return v.(string)
}

// Measure runs op once to warm up (its output is the one reported), then
// takes Samples samples, each running op repeatedly for at least d/Samples
// (and at least 3 times), as bench_units.pl does.
func Measure(u Unit, d time.Duration) Result {
	op, done := u.Setup()
	if done != nil {
		defer done()
	}
	sum := sha256.Sum256([]byte(Output(u, op())))
	res := Result{Name: u.Name, OutputSHA256: hex.EncodeToString(sum[:])}
	per := d / Samples
	for s := 0; s < Samples; s++ {
		n := 0
		start := time.Now()
		var elapsed time.Duration
		for n < 3 || elapsed < per {
			op()
			n++
			elapsed = time.Since(start)
		}
		res.Iterations += n
		res.Samples = append(res.Samples, float64(elapsed.Nanoseconds())/float64(n))
	}
	sorted := append([]float64(nil), res.Samples...)
	sort.Float64s(sorted)
	res.NsPerOp, res.MinNs, res.MaxNs = sorted[len(sorted)/2], sorted[0], sorted[len(sorted)-1]
	return res
}
