// Package benchunits is the set of unit micro-benchmarks shared with the
// Perl original (conformance/perl/bench_units.pl has a unit of each name
// doing the same work with the Perl modules GADS uses), so that the cost of
// the building blocks can be compared:
//
//	go test -run '^$' -bench . ./internal/benchunits    # testing.B
//	go run ./cmd/gads-bench units -out units-go.json    # JSON, for gads-bench compare
//
// The db/ and calc/ units time engine calls on the database of a fixture
// scenario (conformance/bench/fixtures/units_db.yaml) set up by the
// conformance runner; the processing as a whole (records, searches, the web
// application) is measured by the benchmark scenarios (conformance/bench).
//
// Each unit's operation returns its result, which Output renders as text;
// the SHA-256 of that text is reported with the times, so that gads-bench
// compare can check that the Perl and Go units did the same work.
package benchunits

