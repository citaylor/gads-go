// The JSON units encode Rows(1000) as the application does (gads.EncodeJSON:
// sorted keys, no HTML escaping) and decode that encoding; the Perl units do
// the same (canonical JSON), so both produce exactly the bytes of JSONSHA256.
const JSONSHA256 = "23a4577225cf2566007c5e0736432e011a858a44b5995239bb506eb80ba4a70e"

// Unit is a benchmark: Setup prepares its data and returns the operation
// that is timed, which returns its result, and a function to release what
// it set up (or nil). Output renders a result as the text compared with the
// Perl unit's (nil: the result is a string).
type Unit struct {
	Name   string
	Setup  func() (op func() any, done func())
	Output func(any) string
}

// The code given to lua_run, as GADS::Column::Code::eval builds it: the
// variable mapping, then the body of the evaluate function
const (
	luaSimple = "L1integer1 = vars[\"L1integer1\"]\n" +
		" return L1integer1 * 2 "
	luaLoop = "L1integer1 = vars[\"L1integer1\"]\n" +
		"\n  local t = 0\n  for i = 1, 10000 do t = t + (i * L1integer1) % 13 end\n  return t\n"
	luaStrings = "L1string1 = vars[\"L1string1\"]\n" +
		"\n  local parts = {}\n  for w in string.gmatch(L1string1, \"%a+\") do table.insert(parts, string.upper(w)) end\n  return table.concat(parts, \"-\")\n"
)

// A template such as the views use: variables, a loop, conditions and
// filters
const ttTemplate = `<h1>[% title | html %]</h1>
<table>
[% FOREACH row IN rows %]
  <tr class="[% loop.index % 2 ? 'odd' : 'even' %]">
    <td>[% row.id %]</td>
    <td>[% row.name | html %]</td>
    [% IF row.value > 500 %]<td class="high">[% row.value %]</td>[% ELSE %]<td>[% row.value %]</td>[% END %]
  </tr>
[% END %]
</table>
[% rows.size %] rows
`

// Rows is the deterministic data of the JSON, template and CSV units
// (also generated by bench_units.pl)
func Rows(n int) []map[string]any {
	rows := make([]map[string]any, n)
	for i := 0; i < n; i++ {
		rows[i] = map[string]any{
			"id":    i + 1,
			"name":  fmt.Sprintf("Row <%d> & \"name\"", i+1),
			"value": (i * 37) % 1000,
			"tags":  []any{"a", "b", fmt.Sprintf("t%d", i%7)},
		}
	}
	return rows
}

// CSV is the deterministic CSV of the CSV parsing unit
func CSV(n int) string {
	var b strings.Builder
	b.WriteString("string1,integer1,enum1,date1,text1\n")
	for i := 0; i < n; i++ {
		fmt.Fprintf(&b, "\"Name %d, the \"\"first\"\"\",%d,foo%d,2014-%02d-%02d,\"multi\nline %d\"\n",
			i, i*3, i%3+1, i%12+1, i%28+1, i)
	}
	return b.String()
}

const filterJSON = `{"rules":[{"id":"9","type":"integer","operator":"greater","value":"5000"},` +
	`{"condition":"OR","rules":[{"id":"10","type":"string","operator":"equal","value":"foo2"},` +
	`{"id":"12","type":"date","operator":"less","value":"2003-01-01"}]}],"condition":"AND"}`

func luaUnit(name, code string, vars map[string]any) Unit {
	return Unit{Name: name, Setup: func() (func() any, func()) {
		it, err := lua.New()
		if err != nil {
			panic(err)
		}
		cb := lua.Func(func([]any) ([]any, error) { return nil, nil })
		return func() any {
			res, err := it.Run(code, vars, cb, cb)
			if err != nil {
				panic(err)
			}
			return res
		}, it.Close
	}, Output: func(v any) string { return perlString(v.(*lua.RunResult).Return) }}
}

// perlString is the string of a scalar as Perl prints it
func perlString(v any) string {
	switch x := v.(type) {
	case nil:
		return ""
	case float64:
		return strconv.FormatFloat(x, 'g', 15, 64)
	case bool:
		if x {
			return "1"
		}
		return ""
	}
	return fmt.Sprint(v)
}

// FixtureFile is the scenario whose database the db/ and calc/ units use;
// if empty, conformance/bench/fixtures/units_db.yaml is looked for in the
// current directory and its parents.
var FixtureFile string

var fixture struct {
	sync.Mutex
	f *conformance.Fixture
}

func findFixture() string {
	if FixtureFile != "" {
		return FixtureFile
	}
	dir, _ := os.Getwd()
	for {
		for _, rel := range []string{"conformance/bench/fixtures/units_db.yaml", "bench/fixtures/units_db.yaml"} {
			if _, err := os.Stat(filepath.Join(dir, rel)); err == nil {
				return filepath.Join(dir, rel)
			}
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			panic("conformance/bench/fixtures/units_db.yaml not found (set benchunits.FixtureFile)")
		}
		dir = parent
	}
}

// Fixture returns the database of the fixture scenario, setting it up on
// first use (it is shared by the units, which do not change it).
func Fixture() *conformance.Fixture {
	fixture.Lock()
	defer fixture.Unlock()
	if fixture.f == nil {
		f, err := conformance.Setup(findFixture())
		if err != nil {
			panic(err)
		}
		fixture.f = f
	}
	return fixture.f
}

// CloseFixture closes the fixture's database if it was set up.
func CloseFixture() {
	fixture.Lock()
	defer fixture.Unlock()
	if fixture.f != nil {
		fixture.f.Close()
		fixture.f = nil
	}
}

// The columns of the db/ units (those of the page step of b01_records)
var dbColumns = []string{"string1", "integer1", "enum1", "tree1", "date1", "daterange1", "curval1", "calc1"}

// The current ID of the record of db/record_get (the first of the main
// sheet, after the curval sheet's records)
const recordGetID = 51

// dbUnit is a unit timing an engine call on the fixture's main sheet
func dbUnit(name string, op func(e *gads.Engine, l *gads.Layout, u *gads.User, cols []*gads.Column) any, out func(any) string) Unit {
	return Unit{Name: name, Setup: func() (func() any, func()) {
		f := Fixture()
		l, u := f.Layout("main"), f.User("main")
		var cols []*gads.Column
		for _, n := range dbColumns {
			cols = append(cols, f.Column(l, n))
		}
		e := f.Engine()
		return func() any { return op(e, l, u, cols) }, nil
	}, Output: out}
}

// viewUnit is a unit timing an engine call with a view of the fixture
// (the "as" of its view step); setup returns the timed operation
func viewUnit(name, alias string, setup func(e *gads.Engine, l *gads.Layout, u *gads.User, v *gads.View, cols []*gads.Column) func() any, out func(any) string) Unit {
	return Unit{Name: name, Setup: func() (func() any, func()) {
		f := Fixture()
		l, u := f.Layout("main"), f.User("main")
		var cols []*gads.Column
		for _, n := range dbColumns {
			cols = append(cols, f.Column(l, n))
		}
		var v *gads.View
		if alias != "" {
			v = f.View(alias, l)
		}
		return setup(f.Engine(), l, u, v, cols), nil
	}, Output: out}
}

// sortedLinesOutput is the lines sorted (for results in no defined order)
func sortedLinesOutput(v any) string {
	lines := append(recordLines(nil), v.(recordLines)...)
	sort.Strings(lines)
	return strings.Join(lines, "\n")
}

// The current ID of the record of db/record_update (the second of the main
// sheet), and the column it updates
const recordUpdateID = 52

// recordLine is the current ID of a record and the strings of its values
func recordLine(r *gads.Record, cols []*gads.Column) string {
	parts := []string{strconv.FormatInt(r.CurrentID(), 10)}
	for _, c := range cols {
		d := r.GetFieldValue(c)
		if d == nil {
			parts = append(parts, "")
		} else {
			parts = append(parts, d.AsString())
		}
	}
	return strings.Join(parts, "\t")
}

// The result of the records units: the lines of the records retrieved
type recordLines []string

func linesOutput(v any) string { return strings.Join(v.(recordLines), "\n") }

