package perljson

import (
	"encoding/json"
	"os"
	"testing"

	"github.com/ctrlo/gads-go/internal/perltest"
)

// The expected documents are those of JSON::PP->new->canonical->pretty
func TestPretty(t *testing.T) {
	cases := []struct {
		in   any
		want string
	}{
		{map[string]any{"b": int64(1), "a": "x\x01\x7f\"\\/", "c": []any{int64(1), map[string]any{"d": nil}}, "e": map[string]any{}, "f": []any{}},
			"{\n   \"a\" : \"x\\u0001\x7f\\\"\\\\/\",\n   \"b\" : 1,\n   \"c\" : [\n      1,\n      {\n         \"d\" : null\n      }\n   ],\n   \"e\" : {},\n   \"f\" : []\n}\n"},
		{[]any{}, "[]\n"},
		{map[string]any{}, "{}\n"},
		{"s", "\"s\"\n"},
	}
	for _, c := range cases {
		if got := Pretty(c.in); got != c.want {
			t.Errorf("Pretty(%v) =\n%q\nwant\n%q", c.in, got, c.want)
		}
	}
}

// golden is testdata/golden.json: values encoded by JSON::PP, generated by
// conformance/perl/gen_json_golden.pl (also read by gads.EncodeJSON's test)
type golden struct {
	Cases []struct {
		In      map[string]any `json:"in"`
		Compact string         `json:"compact"`
		Pretty  string         `json:"pretty"`
	} `json:"cases"`
}

// TestPrettyGolden checks Pretty against JSON::PP->canonical->pretty
func TestPrettyGolden(t *testing.T) {
	data, err := os.ReadFile("testdata/golden.json")
	if err != nil {
		t.Fatal(err)
	}
	var g golden
	if err := json.Unmarshal(data, &g); err != nil {
		t.Fatal(err)
	}
	for _, c := range g.Cases {
		v, err := perltest.Build(c.In)
		if err != nil {
			t.Fatal(err)
		}
		if got := Pretty(v); got != c.Pretty {
			t.Errorf("Pretty(%v) =\n%s\nPerl\n%s", c.In, got, c.Pretty)
		}
	}
}
