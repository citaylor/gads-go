package yamlxs

import (
	"encoding/json"
	"os"
	"testing"

	"github.com/ctrlo/gads-go/internal/perltest"
)

// The expected documents are those of YAML::XS Dump (perl -MYAML::XS)
func TestDump(t *testing.T) {
	cases := []struct {
		in   any
		want string
	}{
		{map[string]any{"b": int64(1), "a": "x", "c": []any{int64(1), int64(2), map[string]any{"d": nil}}, "e": map[string]any{}, "f": []any{}},
			"---\na: x\nb: 1\nc:\n- 1\n- 2\n- d: ~\ne: {}\nf: []\n"},
		{[]any{"", "~", "true", "1.5", " lead", "a: b", "- x", "multi\nline", "it's", "#c", "plain text", "-1", "0x1F"},
			"---\n- ''\n- '~'\n- 'true'\n- '1.5'\n- ' lead'\n- 'a: b'\n- '- x'\n- \"multi\\nline\"\n- it's\n- '#c'\n- plain text\n- '-1'\n- 0x1F\n"},
		{[]any{[]any{int64(1), int64(2)}, []any{int64(3)}}, "---\n- - 1\n  - 2\n- - 3\n"},
		{"scalar", "--- scalar\n"},
		{map[string]any{}, "--- {}\n"},
	}
	for _, c := range cases {
		if got := Dump(c.in); got != c.want {
			t.Errorf("Dump(%v) =\n%q\nwant\n%q", c.in, got, c.want)
		}
	}
}

// TestDumpGolden checks Dump against YAML::XS, with the cases of
// testdata/golden.json (generated by conformance/perl/gen_yaml_golden.pl)
func TestDumpGolden(t *testing.T) {
	data, err := os.ReadFile("testdata/golden.json")
	if err != nil {
		t.Fatal(err)
	}
	var g struct {
		Cases []struct {
			In  map[string]any `json:"in"`
			Out string         `json:"out"`
		} `json:"cases"`
	}
	if err := json.Unmarshal(data, &g); err != nil {
		t.Fatal(err)
	}
	failed := 0
	for _, c := range g.Cases {
		v, err := perltest.Build(c.In)
		if err != nil {
			t.Fatal(err)
		}
		if got := Dump(v); got != c.Out {
			failed++
			if failed <= 25 {
				t.Errorf("Dump(%v) =\n%s\nYAML::XS\n%s", c.In, got, c.Out)
			}
		}
	}
	if failed > 0 {
		t.Errorf("%d of %d cases differ", failed, len(g.Cases))
	}
}
