package pdf

// GeneratorField is a field of a record, as GADS::PDFGenerator reads its
// presentation: the selected values of a curval (Selected, a list of the
// values of each record, IsSelected when the field has them), or its value,
// or the grade of a RAG
type GeneratorField struct {
	Name       string
	IsSelected bool
	Selected   [][]*string
	Value      *string
	Grade      *string
}

// GeneratorTopic is a topic and its fields ("Other" when none)
type GeneratorTopic struct {
	Name   string
	Fields []GeneratorField
}

// Generator is GADS::PDFGenerator: the PDF of a record, or of a report on
// it
type Generator struct {
	Marking     string
	Logo        []byte
	Title       string
	Subtitle    string
	Topics      []GeneratorTopic
	LastEdited  string // "Last edited by ..."
	GeneratedBy string // "Report generated by ..."
}

// Build is GADS::PDFGenerator build, then the PDF's content
func (g *Generator) Build() ([]byte, error) {
	p, err := NewCtrlO(g.Marking, g.Marking, g.Logo)
	if err != nil {
		return nil, err
	}
	var topMargin float64
	if p.HasLogo() {
		// GADS leaves room below the logo
		topMargin = -30
	}
	p.AddPage()
	p.Heading(g.Title, HeadingOptions{TopMargin: topMargin})
	if perlTrue(g.Subtitle) {
		if err := p.Text(g.Subtitle, 14); err != nil {
			return nil, err
		}
	}
	header := &TableHeader{Justify: "center", FontSize: 12, BgColor: "#007c88", FgColor: "#ffffff"}
	for _, topic := range g.Topics {
		name := topic.Name
		fields := TableData{{&name}}
		width := 0
		for _, f := range topic.Fields {
			fname := f.Name
			if f.IsSelected {
				first := true
				for _, values := range f.Selected {
					if width < len(values)+1 {
						width = len(values) + 1
					}
					label := ""
					if first {
						label = fname
					}
					fields = append(fields, append([]*string{&label}, values...))
					first = false
				}
				continue
			}
			if f.Value != nil && perlTrue(*f.Value) {
				fields = append(fields, []*string{&fname, f.Value})
			} else {
				fields = append(fields, []*string{&fname, f.Grade})
			}
			if width < 2 {
				width = 2
			}
		}
		var colspan [][]int
		for i, d := range fields {
			has := len(d)
			gap := width - has + 1
			for j := 0; j < gap; j++ {
				d = append(d, nil)
			}
			fields[i] = d
			row := make([]int, has)
			row[has-1] = gap + 1
			colspan = append(colspan, row)
		}
		if err := p.Table(fields, TableOptions{
			Header: header, BorderC: "#007C88", HBorderW: 1, BgColorOdd: "#f9f9f9",
			CellColspan: colspan, Size: "4cm *",
		}); err != nil {
			return nil, err
		}
	}
	if err := p.Text(g.LastEdited, 10); err != nil {
		return nil, err
	}
	if err := p.Text(g.GeneratedBy, 10); err != nil {
		return nil, err
	}
	return p.Content(), nil
}
